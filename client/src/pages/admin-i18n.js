export const t = (key, lang) =>
  ADMIN_STRINGS[key]?.[lang] || ADMIN_STRINGS[key]?.en || key;

export const tf = (key, lang, replacements) => {
  let str = t(key, lang);
  for (const [k, v] of Object.entries(replacements)) {
    str = str.replace(`{${k}}`, v);
  }
  return str;
};
