const ensureSchema = async (client) => {
    await client.query('CREATE EXTENSION IF NOT EXISTS pgcrypto');

    await client.query(`
        CREATE TABLE IF NOT EXISTS hens (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            image_url TEXT,
            stock INTEGER NOT NULL DEFAULT 0,
            is_active BOOLEAN NOT NULL DEFAULT true,
            created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
        )
    `);
    await client.query(`
        CREATE UNIQUE INDEX IF NOT EXISTS hens_name_unique_idx
        ON hens (name)
    `);

    await client.query(`
        CREATE TABLE IF NOT EXISTS customers (
            id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
            name TEXT NOT NULL,
            phone TEXT NOT NULL,
            email TEXT,
            address TEXT,
            created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
        )
    `);
    await client.query(`
        DO $$
        DECLARE
            phone_constraint_name TEXT;
        BEGIN
            SELECT tc.constraint_name
            INTO phone_constraint_name
            FROM information_schema.table_constraints tc
            INNER JOIN information_schema.key_column_usage kcu
                ON kcu.constraint_name = tc.constraint_name
               AND kcu.table_schema = tc.table_schema
               AND kcu.table_name = tc.table_name
            WHERE tc.table_schema = current_schema()
              AND tc.table_name = 'customers'
              AND tc.constraint_type = 'UNIQUE'
              AND kcu.column_name = 'phone'
            ORDER BY tc.constraint_name
            LIMIT 1;

            IF phone_constraint_name IS NOT NULL THEN
                EXECUTE format('ALTER TABLE customers DROP CONSTRAINT %I', phone_constraint_name);
            END IF;
        END $$;
    `);
    await client.query(`
        CREATE INDEX IF NOT EXISTS customers_phone_idx
        ON customers (phone)
    `);

    await client.query(`
        CREATE TABLE IF NOT EXISTS pickup_dates (
            id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
            date_value DATE NOT NULL,
            location TEXT NOT NULL,
            is_active BOOLEAN NOT NULL DEFAULT true,
            created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
        )
    `);
    await client.query(`
        CREATE UNIQUE INDEX IF NOT EXISTS pickup_dates_date_location_unique_idx
        ON pickup_dates (date_value, location)
    `);

    await client.query(`
        CREATE TABLE IF NOT EXISTS pickup_stock (
            id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
            pickup_date_id UUID NOT NULL REFERENCES pickup_dates(id) ON DELETE CASCADE,
            hen_id INTEGER NOT NULL REFERENCES hens(id) ON DELETE CASCADE,
            stock INTEGER NOT NULL DEFAULT 0,
            created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
            UNIQUE (pickup_date_id, hen_id)
        )
    `);

    await client.query(`
        CREATE SEQUENCE IF NOT EXISTS orders_order_number_seq
    `);

    await client.query(`
        CREATE TABLE IF NOT EXISTS orders (
            id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
            order_number BIGINT,
            customer_id UUID REFERENCES customers(id),
            customer_email TEXT,
            total_cents INTEGER NOT NULL DEFAULT 0,
            items JSONB NOT NULL DEFAULT '[]'::jsonb,
            status TEXT DEFAULT 'pending',
            pickup_date DATE,
            pickup_location TEXT,
            payment_type TEXT DEFAULT 'full',
            amount_paid_cents INTEGER,
            amount_due_cents INTEGER,
            language TEXT DEFAULT 'en',
            stripe_payment_id TEXT,
            confirmation_email_sent_at TIMESTAMP WITH TIME ZONE,
            created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
        )
    `);
    await client.query(`
        CREATE UNIQUE INDEX IF NOT EXISTS orders_order_number_unique_idx
        ON orders (order_number)
    `);
    await client.query(`
        CREATE OR REPLACE FUNCTION assign_order_number_for_active_order()
        RETURNS TRIGGER AS $$
        BEGIN
            IF TG_OP = 'UPDATE'
               AND OLD.order_number IS NOT NULL
               AND NEW.order_number IS DISTINCT FROM OLD.order_number THEN
                RAISE EXCEPTION 'order_number is immutable once assigned';
            END IF;

            IF NEW.order_number IS NULL THEN
                IF LOWER(COALESCE(NEW.status, 'pending')) NOT IN ('cancelled', 'reserved', 'archived') THEN
                    NEW.order_number := nextval('orders_order_number_seq');
                END IF;
            END IF;

            RETURN NEW;
        END;
        $$ LANGUAGE plpgsql
    `);
    await client.query(`
        DROP TRIGGER IF EXISTS orders_assign_order_number_before_write ON orders
    `);
    await client.query(`
        CREATE TRIGGER orders_assign_order_number_before_write
        BEFORE INSERT OR UPDATE OF status, order_number
        ON orders
        FOR EACH ROW
        EXECUTE FUNCTION assign_order_number_for_active_order()
    `);
    await client.query(`
        CREATE INDEX IF NOT EXISTS orders_pickup_status_idx
        ON orders (pickup_date, pickup_location, LOWER(COALESCE(status, 'pending')))
    `);
};

const seedHens = async (client) => {
    const henByName = new Map();
    for (const hen of hensSeed) {
        const result = await client.query(
            `
            INSERT INTO hens (name, image_url, stock, is_active)
            VALUES ($1, $2, $3, true)
            ON CONFLICT (name) DO UPDATE
            SET image_url = EXCLUDED.image_url,
                stock = EXCLUDED.stock,
                is_active = true
            RETURNING id, name, stock
            `,
            [hen.name, hen.image_url, hen.stock]
        );
        henByName.set(hen.name, result.rows[0]);
    }
    return henByName;
};

const seedPickupDatesAndStock = async (client, henByName) => {
    const pickupDates = [];
    for (const daysAhead of pickupDateOffsets) {
        const dateValue = buildFutureDate(daysAhead);
        for (const location of locations) {
            const result = await client.query(
                `
                INSERT INTO pickup_dates (date_value, location, is_active)
                VALUES ($1, $2, true)
                ON CONFLICT (date_value, location) DO UPDATE
                SET is_active = true
                RETURNING id, date_value, location
                `,
                [dateValue, location]
            );
            pickupDates.push({
                ...result.rows[0],
                dateIndex: pickupDates.length
            });
        }
    }

    const hens = Array.from(henByName.values());
    for (let dateIdx = 0; dateIdx < pickupDates.length; dateIdx += 1) {
        const pickup = pickupDates[dateIdx];
        for (const hen of hens) {
            const isBristol = String(pickup.location).toLowerCase() === 'bristol';
            const baseline = Number(hen.stock || 0);
            const stock = Math.max(
                baseline - (dateIdx * 6) - (isBristol ? 12 : 0),
                0
            );
            await client.query(
                `
                INSERT INTO pickup_stock (pickup_date_id, hen_id, stock)
                VALUES ($1, $2, $3)
                ON CONFLICT (pickup_date_id, hen_id)
                DO UPDATE SET stock = EXCLUDED.stock
                `,
                [pickup.id, hen.id, stock]
            );
        }
    }

    return pickupDates;
};

const seedCustomers = async (client) => {
    const customerByEmail = new Map();
    for (const customer of customersSeed) {
        const result = await client.query(
            `
            INSERT INTO customers (name, phone, email, address)
            VALUES ($1, $2, $3, $4)
            ON CONFLICT (phone) DO UPDATE
            SET name = EXCLUDED.name,
                email = EXCLUDED.email,
                address = EXCLUDED.address
            RETURNING id, name, email
            `,
            [customer.name, customer.phone, customer.email, customer.address]
        );
        customerByEmail.set(customer.email, result.rows[0]);
    }
    return customerByEmail;
};

const buildLine = (hen, quantity, unitCents) => ({
    id: Number(hen.id),
    name: String(hen.name),
    quantity,
    unit_cents: unitCents,
    line_cents: unitCents * quantity
});

