const printSummary = async (client) => {
    const [hens, dates, stocks, customers, orders] = await Promise.all([
        client.query('SELECT COUNT(*)::int AS count FROM hens'),
        client.query('SELECT COUNT(*)::int AS count FROM pickup_dates'),
        client.query('SELECT COUNT(*)::int AS count FROM pickup_stock'),
        client.query('SELECT COUNT(*)::int AS count FROM customers'),
        client.query('SELECT COUNT(*)::int AS count FROM orders')
    ]);

    console.log('Seed summary:');
    console.log(`- hens: ${hens.rows[0].count}`);
    console.log(`- pickup_dates: ${dates.rows[0].count}`);
    console.log(`- pickup_stock rows: ${stocks.rows[0].count}`);
    console.log(`- customers: ${customers.rows[0].count}`);
    console.log(`- orders: ${orders.rows[0].count}`);
};

async function run() {
    const client = await pool.connect();
    try {
        await client.query('BEGIN');
        await ensureSchema(client);
        const henByName = await seedHens(client);
        const pickupDates = await seedPickupDatesAndStock(client, henByName);
        const customerByEmail = await seedCustomers(client);
        const orderResult = await seedOrders(client, {
            henByName,
            customerByEmail,
            pickupDates
        });
        await client.query('COMMIT');

        if (orderResult.skipped) {
            console.log('Dummy orders already exist, skipped order inserts.');
        } else {
            console.log(`Inserted ${orderResult.inserted} dummy orders.`);
        }

        await printSummary(client);
    } catch (err) {
        await client.query('ROLLBACK');
        throw err;
    } finally {
        client.release();
        await pool.end();
    }
}

run().catch((err) => {
    console.error('Dummy data seed failed:', err);
    process.exit(1);
});
